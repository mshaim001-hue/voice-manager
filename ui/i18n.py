def normalize_ui_lang(code: str | None) -> str:
    c = (code or "ru").lower().strip()
    return c if c in STRINGS else "ru"


def t(lang: str, key: str, **kwargs: Any) -> str:
    pack = STRINGS[normalize_ui_lang(lang)]
    text = pack.get(key) or STRINGS["ru"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
